function normalize(value: string) {
  return value.replace(/[\u2019\u2018]/g, "'").replace(/\s+/g, ' ').trim()
}

const englishByNormalizedText = new Map(
  Object.entries(english).map(([source, translation]) => [normalize(source), translation]),
)
const englishByLowercaseText = new Map(
  Object.entries(english).map(([source, translation]) => [normalize(source).toLocaleLowerCase('fr-FR'), translation]),
)

function translate(value: string) {
  const key = normalize(value)
  const exact = englishByNormalizedText.get(key)
  if (exact) return exact
  const matchingCase = englishByLowercaseText.get(key.toLocaleLowerCase('fr-FR'))
  if (matchingCase) {
    return key && key === key.toLocaleUpperCase('fr-FR')
      ? matchingCase.toLocaleUpperCase('en-US')
      : matchingCase
  }

  const dynamic = [
    [/^Bonjour (.+?)(?:\s*👋)?$/u, 'Hello $1'],
    [/^Bienvenue dans (.+)$/u, 'Welcome to $1'],
    [/^ESPACE ENSEIGNANT$/u, 'TEACHER WORKSPACE'],
    [/^ESPACE ÉTUDIANT$/u, 'STUDENT WORKSPACE'],
    [/^ESPACE (\w+)$/u, 'WORKSPACE $1'],
    [/^(\d+) inscriptions?$/u, '$1 enrollments'],
    [/^(\d+) étudiants?$/u, '$1 students'],
    [/^(\d+) enseignants?$/u, '$1 teachers'],
    [/^(\d+) formations?$/u, '$1 courses'],
    [/^(\d+) sessions?$/u, '$1 sessions'],
    [/^(\d+) à compléter$/u, '$1 to complete'],
    [/^Après l’étape précédente$/u, 'After the previous step'],
    [/^Lecture seule · session temporaire jusqu’à (.+)$/u, 'Read-only · temporary session until $1'],
    [/^Expire le (.+)$/u, 'Expires on $1'],
  ] as const

  for (const [pattern, replacement] of dynamic) {
    if (pattern.test(key)) return key.replace(pattern, replacement)
  }
  return null
}

