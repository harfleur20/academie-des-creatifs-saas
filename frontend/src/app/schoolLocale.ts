let pendingNodes: Node[] = []

function restoreOriginalLanguage() {
  observer?.disconnect()
  for (const node of changedTextNodes) {
    const original = originalText.get(node)
    if (original !== undefined && node.isConnected && node.textContent === translatedText.get(node)) {
      node.textContent = original
    }
    originalText.delete(node)
    translatedText.delete(node)
  }
  for (const element of changedElements) {
    const originals = originalAttributes.get(element)
    if (!originals || !element.isConnected) continue
    const translations = translatedAttributes.get(element)
    originals.forEach((value, name) => {
      if (element.getAttribute(name) === translations?.get(name)) element.setAttribute(name, value)
    })
    originals.clear()
    translations?.clear()
  }
  changedTextNodes.clear()
  changedElements.clear()
  pendingNodes = []
  scheduled = false
  observer = null
}

function isExcluded(element: Element) {
  return Boolean(element.closest('input, textarea, script, style, code, pre, [contenteditable="true"], [data-no-translate]'))
}

function translateTextNode(node: Text) {
  const current = node.textContent ?? ''
  const previousTranslation = translatedText.get(node)
  const wasTranslated = previousTranslation === current
  const original = wasTranslated ? originalText.get(node) ?? current : current

  if (!wasTranslated && changedTextNodes.has(node)) {
    changedTextNodes.delete(node)
    originalText.delete(node)
    translatedText.delete(node)
  }

  const translated = translate(original)
  if (!translated || translated === normalize(current)) return

  originalText.set(node, original)
  changedTextNodes.add(node)
  const leading = original.match(/^\s*/)?.[0] ?? ''
  const trailing = original.match(/\s*$/)?.[0] ?? ''
  const next = `${leading}${translated}${trailing}`
  node.textContent = next
  translatedText.set(node, next)
}

function translateElement(element: Element) {
  if (element.closest('[data-no-translate]')) return

  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement
      if (!parent || isExcluded(parent)) return NodeFilter.FILTER_REJECT
      return node.textContent?.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT
    },
  })

  let node: Node | null
  while ((node = walker.nextNode())) translateTextNode(node as Text)

  const elements = [element, ...element.querySelectorAll('*')]
  for (const item of elements) {
    if (item.closest('[data-no-translate]')) continue
    for (const name of attributes) {
      const value = item.getAttribute(name)
      if (!value) continue

      const originals = originalAttributes.get(item)
      const previousTranslation = translatedAttributes.get(item)?.get(name)
      const wasTranslated = value === previousTranslation
      const original = wasTranslated ? originals?.get(name) ?? value : value
      if (!wasTranslated && originals?.has(name)) {
        originals.delete(name)
        translatedAttributes.get(item)?.delete(name)
      }

      const translated = translate(original)
      if (!translated || translated === value) continue

      let storedOriginals = originalAttributes.get(item)
      if (!storedOriginals) {
        storedOriginals = new Map()
        originalAttributes.set(item, storedOriginals)
      }
      storedOriginals.set(name, original)
      let storedTranslations = translatedAttributes.get(item)
      if (!storedTranslations) {
        storedTranslations = new Map()
        translatedAttributes.set(item, storedTranslations)
      }
      storedTranslations.set(name, translated)
      changedElements.add(item)
      item.setAttribute(name, translated)
    }
  }
}

function scanAddedNode(node: Node) {
  if (node instanceof Element) translateElement(node)
  else if (node instanceof Text && node.parentElement && !isExcluded(node.parentElement)) {
    translateTextNode(node)
  }
}

function scheduleTranslation(records: MutationRecord[]) {
  records.forEach((record) => {
    if (record.type === 'characterData' || record.type === 'attributes') pendingNodes.push(record.target)
    pendingNodes.push(...Array.from(record.addedNodes))
  })
  if (scheduled) return
  scheduled = true
  requestAnimationFrame(() => {
    scheduled = false
    const nodes = pendingNodes
    pendingNodes = []
    nodes.forEach(scanAddedNode)
  })
}

export function setSchoolInterfaceLocale(locale: string | null | undefined) {
  const nextLocale = locale === 'en-US' || locale === 'fr-CM' ? locale : 'fr-FR'
  if (nextLocale === currentLocale && observer) return
  restoreOriginalLanguage()
  currentLocale = nextLocale
  document.documentElement.lang = currentLocale
  if (currentLocale !== 'en-US' || !document.body) return

  translateElement(document.body)
  observer = new MutationObserver(scheduleTranslation)
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: [...attributes],
  })
}

export function activeSchoolLocale() {
  return currentLocale
}

/** An element's text as the app wrote it: translating it to English does not change it. */
export function untranslatedText(element: Element) {
  let text = ''
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT)
  let node: Node | null
  while ((node = walker.nextNode())) {
    const textNode = node as Text
    const current = textNode.textContent ?? ''
    text += translatedText.get(textNode) === current ? originalText.get(textNode) ?? current : current
  }
  return text
}
